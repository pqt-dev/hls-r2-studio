<?php

/**
 * Generates the code point -> ASCII transliteration table (TypeScript syntax) that
 * src-tauri/src/pipeline/ascii_table.rs was derived from (the legacy TS slugify() used it
 * directly), extracted from Laravel's Str::ascii() (which uses
 * voku/portable-ascii with the 'en' language). Only non-empty, non-identity mappings are kept;
 * every other non-ASCII code point is dropped by the slug pipeline, exactly like PHP does.
 *
 * Usage (read-only, no DB needed), from the repository root (needs the Laravel vendor/ directory):
 *   php desktop-app-rs/scripts/gen-ascii-table.php > /tmp/ascii-table.ts
 *   The output lists the same code point -> string entries as ascii_table.rs (676 entries);
 *   compare it against that file when regenerating (the Rust file has its own syntax).
 */

require __DIR__.'/../../vendor/autoload.php';

use Illuminate\Support\Str;

$ranges = [
    [0x00A0, 0x024F], // Latin-1 Supplement, Latin Extended-A and B
    [0x0370, 0x052F], // Greek, Cyrillic
    [0x1E00, 0x1EFF], // Latin Extended Additional (includes all Vietnamese)
    [0x2000, 0x218F], // Punctuation, super/subscripts, currency, letterlike, number forms
    [0xFB00, 0xFB06], // Latin ligatures
];

$entries = [];

foreach ($ranges as [$from, $to]) {
    for ($cp = $from; $cp <= $to; $cp++) {
        $char = mb_chr($cp, 'UTF-8');
        $ascii = Str::ascii($char);

        if ($ascii === '' || $ascii === $char) {
            continue;
        }

        $entries[$cp] = $ascii;
    }
}

echo "// GENERATED by desktop-app-rs/scripts/gen-ascii-table.php from Laravel Str::ascii(). Do not edit by hand.\n";
echo "export const ASCII_TABLE: Readonly<Record<number, string>> = {\n";

foreach ($entries as $cp => $ascii) {
    printf("    0x%04X: %s,\n", $cp, json_encode($ascii, JSON_UNESCAPED_SLASHES));
}

echo "};\n";
